import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '../lib/playwright-smoke.mjs';

const htmlPath = process.argv[2] || 'pages/procurement/service-settlement.html';
const reportDir = path.resolve('outputs/reports/visual/procurement');
fs.mkdirSync(reportDir, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(5000);
page.setDefaultNavigationTimeout(15000);
const errors = [];
const expect = (condition, message) => { if (!condition) errors.push(message); };
page.on('pageerror', (error) => errors.push(`pageerror: ${error.message}`));
page.on('console', (message) => { if (message.type() === 'error') errors.push(`console: ${message.text()}`); });

await page.goto(pathToFileURL(path.resolve(htmlPath)).href, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(250);
const list = page.locator('[data-page-view="list"]');
const table = list.locator('#service-settlement-table');
expect(await list.isVisible(), '服务结算列表未显示');
expect(await table.locator('tbody > tr:visible:not([data-empty-row])').count() === 5, '列表未固定5条/页');
expect(await table.locator('tbody > tr:not([data-empty-row])').count() === 12, '服务结算样例不是12条');
expect((await list.locator('.page-size-select[data-fixed-page-size]').textContent()).trim() === '5条/页', '固定页容量错误');
const searchLabels = await list.locator('#service-settlement-search .form-label').allTextContents().then((items) => items.map((item) => item.trim()));
const headers = await table.locator('thead th').allTextContents().then((items) => items.map((item) => item.trim()).filter(Boolean));
expect(JSON.stringify(searchLabels) === JSON.stringify(['服务结算单号','状态','类型','供应商','结算日期']), `列表查询字段错误: ${searchLabels.join('、')}`);
expect(JSON.stringify(headers) === JSON.stringify(['服务结算单号','状态','类型','结算日期','供应商','创建人','创建时间','操作']), `列表字段错误: ${headers.join('、')}`);
expect(headers.indexOf('状态') === headers.indexOf('服务结算单号') + 1 && headers.indexOf('类型') === headers.indexOf('状态') + 1, '列表单号、状态、类型顺序错误');
expect(!headers.includes('结算金额') && !headers.includes('项目'), '列表仍包含已移除的项目或结算金额');
expect(!await list.locator('[data-act="audit"]').isDisabled() === false && !await list.locator('[data-act="reverse-audit"]').isDisabled() === false, '未选择记录时审核按钮未禁用');

await list.locator('[data-act="create"]').click();
const detail = page.locator('[data-page-view="detail"]');
const basic = detail.locator('[data-tab-panel="basic"] [data-component="DetailForm"]');
expect(await detail.isVisible(), '新增服务结算详情未显示');
const basicLabels = await basic.locator('.form-label').allTextContents().then((items) => items.map((item) => item.trim().replace(/^\*\s*/, '')));
expect(JSON.stringify(basicLabels) === JSON.stringify(['服务结算单号','状态','类型','结算日期','供应商','本次结算金额','创建人','创建时间','审核人','审核时间','所属公司','备注']), `基础信息字段错误: ${basicLabels.join('、')}`);
const items = detail.locator('#service-settlement-items');
const blueButton = items.locator('[data-target="service-order-line-picker"]');
expect(await blueButton.isVisible() && await blueButton.isDisabled(), '未选择类型时蓝字来源按钮未禁用');
await detail.locator('select[data-field="settlementType"]').selectOption('蓝字');
expect(await blueButton.isDisabled(), '未选择供应商时采购订单入口不应启用');
await detail.locator('[data-target="supplier-picker"]').click();
const supplierPicker = page.locator('[data-overlay="supplier-picker"]');
const supplierRow = supplierPicker.locator('tbody > tr:not([data-empty-row])').filter({ hasText: '武汉云帆科技有限公司' }).first();
await supplierRow.locator('[data-row-select]').check();
await supplierPicker.locator('[data-act="confirm-supplier"]').click();
expect((await detail.locator('[data-field="supplierName"]').inputValue()) === '武汉云帆科技有限公司', '供应商选择未回填');
expect(!await blueButton.isDisabled(), '选择类型和供应商后采购订单入口未启用');
await blueButton.click();
const orderPicker = page.locator('[data-overlay="service-order-line-picker"]');
expect(await orderPicker.isVisible(), '采购订单选择弹窗未显示');
const orderSearchLabels = await orderPicker.locator('[data-component="ProSearchForm"] .form-label').allTextContents().then((values) => values.map((value) => value.trim()));
const orderHeaders = await orderPicker.locator('#service-order-line-table thead th').allTextContents().then((values) => values.map((value) => value.trim()).filter(Boolean));
expect(JSON.stringify(orderSearchLabels) === JSON.stringify(['采购订单','合同名称','项目','物资名称']), `采购订单弹窗查询字段错误: ${orderSearchLabels.join('、')}`);
expect(JSON.stringify(orderHeaders) === JSON.stringify(['订单日期','物资名称','规格','单位','订单数量','已净结算数量','可结算数量','项目','合同名称','采购订单','订单行']), `采购订单弹窗列表字段错误: ${orderHeaders.join('、')}`);
const orderRows = orderPicker.locator('tbody > tr:visible:not([data-empty-row])');
expect(await orderRows.count() >= 1, '服务采购订单来源不足');
const orderValues = await orderRows.evaluateAll((rows) => rows.map((row) => JSON.parse(row.dataset.rowValue || '{}')));
expect(orderValues.every((row) => row.company === '昕彤赋能（武汉）设计研究有限公司' && row.supplierName === '武汉云帆科技有限公司' && row.purchaseCategory === '服务' && Number(row.availableQuantity) > 0), '采购订单来源未按公司、供应商或可结算数量过滤');
await orderRows.first().locator('[data-row-select]').check();
await orderPicker.locator('[data-act="confirm-order-lines"]').click();
expect(await items.locator('tbody > tr:not([data-empty-row])').count() === 1, '蓝字订单行未带入结算明细');
const blueValues = await items.locator('tbody > tr:not([data-empty-row])').evaluateAll((rows) => rows.map((row) => JSON.parse(row.dataset.rowValue || '{}')));
expect(Number(blueValues[0].settlementQuantity) > 0 && Number(blueValues[0].taxIncludedAmount) > 0, '蓝字结算数量或金额未为正数');
expect((await detail.locator('[data-field="supplierName"]').inputValue()) === blueValues[0].supplierName, '选择订单后未回填供应商');
const detailHeaders = await items.locator('thead th').allTextContents().then((values) => values.map((value) => value.trim()).filter(Boolean));
const detailBusinessHeaders = detailHeaders.filter((header) => header !== '序号');
expect(JSON.stringify(detailBusinessHeaders) === JSON.stringify(['物资名称','规格','单位','可结算数量','结算数量','含税单价','价税合计','备注','采购订单','订单行','蓝字结算单','结算单行','操作']), `蓝字明细字段错误: ${detailHeaders.join('、')}`);
expect(detailHeaders[0] === '序号' && detailHeaders[1] === '物资名称', `序号未位于勾选列后、物资名称前: ${detailHeaders.join('、')}`);
expect((await items.locator('tbody > tr:not([data-empty-row]) [data-column="sequence"]').first().textContent()).trim() === '1', '首条服务结算明细序号不是1');
const quantityInput = items.locator('tbody > tr:not([data-empty-row]) [data-field="settlementQuantity"]');
const availableQuantity = Number(blueValues[0].availableQuantity);
await quantityInput.fill(String(availableQuantity / 2));
const expectedBlueAmount = (availableQuantity / 2 * Number(blueValues[0].taxIncludedUnitPrice)).toFixed(2);
expect((await items.locator('tbody > tr:not([data-empty-row]) [data-column="taxIncludedAmount"]').textContent()).trim() === expectedBlueAmount, '蓝字价税合计未按结算数量实时计算');
expect((await detail.locator('[data-field="settlementAmount"]').inputValue()) === expectedBlueAmount, '本次结算金额未同步价税合计');
await quantityInput.fill(String(availableQuantity + 1));
await detail.locator('[data-act="save"]').click();
expect(await detail.isVisible(), '蓝字超可结算数量仍提交成功');
await quantityInput.fill(String(availableQuantity / 2));
await page.screenshot({ path: path.join(reportDir, 'service-settlement-detail-blue.png') });

await detail.locator('select[data-field="settlementType"]').selectOption('红字');
expect(await items.locator('tbody > tr:not([data-empty-row])').count() === 0, '切换红字后未清空蓝字明细');
const redButton = items.locator('[data-target="blue-service-settlement-picker"]');
expect(await redButton.isVisible() && !await redButton.isDisabled(), '红字来源入口未启用');
await redButton.click();
const bluePicker = page.locator('[data-overlay="blue-service-settlement-picker"]');
const blueSearchLabels = await bluePicker.locator('[data-component="ProSearchForm"] .form-label').allTextContents().then((values) => values.map((value) => value.trim()));
const blueHeaders = await bluePicker.locator('#blue-service-settlement-table thead th').allTextContents().then((values) => values.map((value) => value.trim()).filter(Boolean));
expect(JSON.stringify(blueSearchLabels) === JSON.stringify(['采购订单','蓝字结算单','合同名称','项目','物资名称']), `蓝字结算单弹窗查询字段错误: ${blueSearchLabels.join('、')}`);
expect(JSON.stringify(blueHeaders) === JSON.stringify(['结算日期','物资名称','规格','单位','结算数量','已红冲数量','可红冲数量','项目','合同名称','蓝字结算单','结算单行','采购订单','订单行']), `蓝字结算单弹窗列表字段错误: ${blueHeaders.join('、')}`);
const redRows = bluePicker.locator('#blue-service-settlement-table tbody > tr:visible:not([data-empty-row])');
expect(await redRows.count() >= 1, '可冲销的蓝字服务结算行不足');
await redRows.first().locator('[data-row-select]').check({ force: true });
await bluePicker.locator('[data-act="confirm-blue-settlement-lines"]').click();
const redValues = await items.locator('tbody > tr:not([data-empty-row])').evaluateAll((rows) => rows.map((row) => JSON.parse(row.dataset.rowValue || '{}')));
expect(Number(redValues[0].settlementQuantity) < 0 && Number(redValues[0].taxIncludedAmount) < 0 && redValues[0].originalSettlementNo, '红字结算未保留负数及原蓝字来源');
const redHeaders = await items.locator('thead th').allTextContents().then((values) => values.map((value) => value.trim()).filter(Boolean));
expect(redHeaders.includes('可红冲数量') && !redHeaders.includes('可结算数量'), '红字明细动态数量表头错误');
const redQuantityInput = items.locator('tbody > tr:not([data-empty-row]) [data-field="settlementQuantity"]');
await redQuantityInput.fill('0.50');
expect(Number(await redQuantityInput.inputValue()) === -0.5, '红字录入正数后未自动转换为负数');
expect(Number(await detail.locator('[data-field="settlementAmount"]').inputValue()) < 0, '红字本次结算金额未自动汇总为负数');
await redQuantityInput.fill(String(Number(redValues[0].availableQuantity) + 1));
await detail.locator('[data-act="save"]').click();
expect(await detail.isVisible(), '红字绝对值超过可红冲数量仍提交成功');
await redQuantityInput.fill('-0.50');
await page.screenshot({ path: path.join(reportDir, 'service-settlement-detail-red.png') });

await detail.locator('[data-act="back-list"]').click();
const waitRow = table.locator('tbody > tr:has(a[data-row-id="SS001"])');
await waitRow.locator('[data-row-select]').check();
await list.locator('[data-act="audit"]').click();
await page.locator('[data-overlay="audit-settlement-modal"] [data-act="confirm-status"]').click();
expect(await waitRow.getAttribute('data-row-status') === '审核', '审核未变更为审核');
const audited = JSON.parse(await waitRow.getAttribute('data-row-value') || '{}');
expect(Boolean(audited.auditUser) && /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(audited.auditTime || ''), '审核人或审核时间未写入');

const widePage = await browser.newPage({ viewport: { width: 2048, height: 1200 }, deviceScaleFactor: 1 });
widePage.setDefaultNavigationTimeout(15000);
await widePage.goto(pathToFileURL(path.resolve(htmlPath)).href, { waitUntil: 'domcontentloaded' });
await widePage.waitForTimeout(250);
const wideMetrics = await widePage.evaluate(() => ({ clientWidth: document.documentElement.clientWidth, scrollWidth: document.documentElement.scrollWidth }));
expect(wideMetrics.scrollWidth <= wideMetrics.clientWidth + 1, '2048px 视口存在页面级横向溢出');
expect(await widePage.locator('#service-settlement-table tbody > tr:visible:not([data-empty-row])').count() === 5, '2048px 视口列表未固定5条/页');
await widePage.locator('#service-settlement-table [data-column="settlementNo"] a').first().click();
const wideDetail = widePage.locator('[data-page-view="detail"]');
expect(await wideDetail.isVisible(), '2048px 视口未打开服务结算详情');
expect((await wideDetail.locator('#service-settlement-items thead th').allTextContents()).map((value) => value.trim()).filter(Boolean)[0] === '序号', '2048px 明细序号列位置错误');
expect((await wideDetail.locator('#service-settlement-items tbody [data-column="sequence"]').first().textContent()).trim() === '1', '2048px 明细首行序号不是1');
await widePage.screenshot({ path: path.join(reportDir, 'service-settlement-detail-blue-2048.png') });
await widePage.close();

const menuPage = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
menuPage.setDefaultNavigationTimeout(15000);
await menuPage.goto(pathToFileURL(path.resolve('menu/index.html')).href, { waitUntil: 'domcontentloaded' });
const procurementMenu = menuPage.locator('.menu-primary', { hasText: '采购管理' });
await procurementMenu.click();
const serviceSettlementMenu = procurementMenu.locator('xpath=..').locator('.submenu button', { hasText: '服务结算' });
expect(await serviceSettlementMenu.getAttribute('data-path') === 'procurement/service-settlement.html', '服务结算菜单路径错误');
await serviceSettlementMenu.click();
await menuPage.waitForTimeout(600);
expect((await menuPage.locator('#contentFrame').getAttribute('src'))?.endsWith('procurement/service-settlement.html'), 'iframe 未打开服务结算页面');
expect(await menuPage.locator('#breadcrumbPage').innerText() === '服务结算', '服务结算面包屑错误');
await menuPage.close();

await Promise.race([
  browser.close().catch(() => undefined),
  new Promise((resolve) => setTimeout(resolve, 3000))
]);
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
console.log('服务结算专项冒烟通过');
process.exit(0);
