import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '../lib/playwright-smoke.mjs';

const htmlPath = path.resolve('pages/income/project-settlement.html');
const menuPath = path.resolve('menu/index.html');
const reportDir = path.resolve('outputs/reports/visual');
const screenshotPath = path.join(reportDir, 'project-settlement-list.png');
const detailScreenshotPath = path.join(reportDir, 'project-settlement-detail-1440.png');
const wideDetailScreenshotPath = path.join(reportDir, 'project-settlement-detail-2048.png');
fs.mkdirSync(reportDir, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(5000);
const errors = [];
const expect = (condition, message) => { if (!condition) errors.push(message); };

await page.goto(pathToFileURL(htmlPath).href, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(300);
const list = page.locator('[data-page-view="list"]');
const table = list.locator('#settlement-table');
expect(await table.isVisible(), '项目结算单列表未显示');
expect(await list.locator('[data-component="BizfinChain"]').count() === 0, '列表仍显示业务流程区');
expect(await list.locator('[data-act="export"]').count() === 0, '列表仍显示导出操作');
expect(await list.locator('[data-act="audit"]').count() === 1 && await list.locator('[data-act="reverse-audit"]').count() === 1, '列表缺少审核或反审核操作');
expect(await list.locator('[data-act="audit"]').isDisabled() && await list.locator('[data-act="reverse-audit"]').isDisabled(), '未选中记录时审核操作应禁用');
const labels = await list.locator('#search .form-label').allTextContents().then((items) => items.map((item) => item.trim()));
expect(JSON.stringify(labels) === JSON.stringify(['项目结算单号', '状态', '合同名称', '项目名称', '客户名称', '结算日期']), '查询条件不符合要求');
const headers = await table.locator('thead th').allTextContents().then((items) => items.map((item) => item.trim()).filter(Boolean));
expect(JSON.stringify(headers) === JSON.stringify(['项目结算单号', '状态', '结算日期', '合同名称', '项目名称', '客户名称', '收款计划', '计划金额', '本次结算金额', '创建人', '创建时间', '操作']), '列表字段或顺序不符合要求');
expect(await table.getByText('5条/页', { exact: true }).count() === 1, '列表缺少固定5条/页标识');
expect(await table.locator('tbody > tr:not([hidden])').count() === 5, '列表首屏不是固定5条');

const pendingRow = table.locator('tbody > tr:has(a[data-row-id="JS1"])');
await pendingRow.locator('[data-row-select]').check();
expect(!(await list.locator('[data-act="audit"]').isDisabled()) && await list.locator('[data-act="reverse-audit"]').isDisabled(), '待审核记录的审核状态限制错误');
await list.locator('[data-act="audit"]').click();
await page.locator('[data-overlay="audit-settlement-modal"] [data-act="confirm-status"]').click();
expect(await pendingRow.getAttribute('data-row-status') === '审核', '审核后状态未更新为审核');
let row = JSON.parse(await pendingRow.getAttribute('data-row-value') || '{}');
expect(Boolean(row.reviewer) && Boolean(row.reviewedAt), '审核后未回填审核人或审核时间');
await pendingRow.locator('[data-row-select]').check();
await page.waitForTimeout(100);
await list.locator('[data-act="reverse-audit"]').click();
await page.locator('[data-overlay="reverse-settlement-modal"] [data-act="confirm-status"]').click();
expect(await pendingRow.getAttribute('data-row-status') === '新增', '反审核后状态未回到新增');
row = JSON.parse(await pendingRow.getAttribute('data-row-value') || '{}');
expect(row.reviewer === '' && row.reviewedAt === '', '反审核后未清空审核信息');

const createText = (await list.locator('[data-act="create"]').innerText()).trim();
await list.locator('[data-act="create"]').click();
const detail = page.locator('[data-page-view="detail"]');
expect(createText === '新增', '新增按钮文案不是新增');
expect(await detail.locator('[data-act="save"]').count() === 1 && (await detail.locator('[data-act="save"]').innerText()).trim() === '保存', '详情保存按钮文案不是保存');
expect(await detail.locator('[data-act="submit"]').count() === 0, '详情仍保留提交按钮');
expect(await detail.locator('[data-field="status"]').first().inputValue() === '新增', '新增详情默认状态不是新增');
const detailLabels = await detail.locator('[data-tab-panel="basic"] .form-label').allTextContents().then((items) => items.map((item) => item.trim().replace(/^\*/, '')));
expect(JSON.stringify(detailLabels) === JSON.stringify(['项目结算单号', '状态', '项目名称', '合同名称', '客户名称', '结算日期', '收款计划', '计划金额', '待结算金额', '本次结算金额', '创建人', '创建时间', '审核人', '审核时间', '所属公司', '备注']), '基础信息字段或顺序不符合要求');
expect(await detail.locator('[data-field="settlementContent"]').count() === 0, '基础信息仍显示结算内容');
expect(await detail.locator('[data-tab="attachments"]').count() === 1, '详情缺少附件页签');
await detail.locator('[data-target="contract-picker"]').click();
await page.locator('[data-overlay="contract-picker"] [data-row-select]').first().check();
await page.locator('[data-overlay="contract-picker"] [data-act="confirm-selection"]').click();
const pendingAmount = await detail.locator('[data-field="pendingAmount"]').inputValue();
expect(await detail.locator('[data-field="receivableAmount"]').inputValue() === pendingAmount, '本次结算金额未默认等于待结算金额');
expect(!await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1), '1440px详情存在页面级横向溢出');
await page.screenshot({ path: detailScreenshotPath, fullPage: true });
await page.setViewportSize({ width: 2048, height: 1152 });
expect(!await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1), '2048px详情存在页面级横向溢出');
expect(await detail.locator('[data-field="settlementContent"]').count() === 0, '2048px详情仍显示结算内容');
expect(await detail.locator('[data-tab="attachments"]').count() === 1, '2048px详情缺少附件页签');
await page.screenshot({ path: wideDetailScreenshotPath, fullPage: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto(pathToFileURL(menuPath).href, { waitUntil: 'domcontentloaded' });
await page.locator('.menu-primary').filter({ hasText: '收入管理' }).click();
await page.locator('button[data-path="income/project-settlement.html"]').click();
const menuFrame = page.frameLocator('#contentFrame');
await menuFrame.locator('[data-page-view="list"] #settlement-table').waitFor({ state: 'visible' });
expect(await menuFrame.locator('[data-page-view="list"] #settlement-table').count() === 1, '菜单入口未在 iframe 打开项目结算单');
await browser.close();
if (errors.length) throw new Error(errors.join('\n'));
console.log(`Project settlement smoke passed: ${screenshotPath}`);
